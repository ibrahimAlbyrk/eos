pub(crate) const DISPLAY: &[&str] = &["block", "inline", "inline-block", "flex", "grid", "none"];
pub(crate) const POSITION: &[&str] = &["relative", "static"];

/// The narrowed values of a property, if it has any.
pub(crate) fn narrowed(property: &str) -> Option<&'static [&'static str]> {
    match property {
        "display" => Some(DISPLAY),
        "position" => Some(POSITION),
        _ => None,
    }
}
