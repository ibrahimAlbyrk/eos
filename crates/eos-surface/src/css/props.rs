/// Properties a page may never set, with why, for the problem it reads.
pub(crate) const REFUSED: &[(&str, &str)] = &[
    ("content", "content= writes text that is not the page's data"),
    ("z-index", "a page may not layer itself over anything"),
    ("cursor", "a page does not change the pointer"),
    ("pointer-events", "a page does not change what the pointer reaches"),
    ("font", "write font-family, font-size and the rest apart, so the family is checked"),
    ("background-attachment", "a page's background does not move"),
];

