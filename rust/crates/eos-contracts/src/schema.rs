//! The JSON Schema bundle of every wire type, for generators outside Rust
//! (`cargo xtask contracts`). Shapes only: lengths, ranges and patterns are
//! enforced by [`Validate`](crate::Validate), not described here.

use schemars::SchemaGenerator;
use serde_json::{Value, json};

#[allow(clippy::wildcard_imports)]
use crate::*;

macro_rules! bundle {
    ($($ty:ty),* $(,)?) => {
        /// `{"$schema", "$defs": {<type name>: <schema>}}` for every type listed in this file.
        pub fn json_schema_bundle() -> Value {
            let mut generator = SchemaGenerator::default();
            $( let _ = generator.subschema_for::<$ty>(); )*
            json!({
                "$schema": "https://json-schema.org/draft/2020-12/schema",
                "$defs": generator.take_definitions(true),
            })
        }
    };
}

