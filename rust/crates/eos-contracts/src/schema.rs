#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_bundle_holds_every_listed_type() {
        let bundle = json_schema_bundle();
        let defs = bundle["$defs"].as_object().unwrap();
        assert!(defs.len() > 600, "{} definitions", defs.len());
        for name in ["AgentEvent", "WorkerRow", "WorkerEventRow", "MessageRequest", "UiConfigResponse", "Condition"] {
            assert!(defs.contains_key(name), "{name}");
        }
        assert_eq!(defs["SideQuestionRequest"]["properties"]["question"]["type"], "string");
    }
}
